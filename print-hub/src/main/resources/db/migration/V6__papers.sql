-- Paper Catalog entries read from the Fiery (GET /papercatalog). Never deleted: papers that disappear
-- from the Fiery are marked inactive so old jobs keep their paper.
CREATE TABLE paper (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fiery_pcmid     VARCHAR(40)  NOT NULL,
    name            VARCHAR(150) NOT NULL,
    width_pt        DOUBLE PRECISION,
    height_pt       DOUBLE PRECISION,
    weight_gsm      VARCHAR(20),
    media_type      VARCHAR(60),
    coating         VARCHAR(60),
    color           VARCHAR(60),
    tray            VARCHAR(20),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    first_seen_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_synced_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_paper_pcmid UNIQUE (fiery_pcmid)
);
