CREATE TABLE customer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20),
    name            VARCHAR(150) NOT NULL,
    phone           VARCHAR(30),
    email           VARCHAR(150),
    company         VARCHAR(150),
    gstin           VARCHAR(20),
    address         VARCHAR(500),
    notes           VARCHAR(2000),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    source          VARCHAR(20)  NOT NULL,          -- WEB or DESKTOP
    portal_user_id  BIGINT REFERENCES app_user (id),  -- customer portal login (optional feature)
    created_by      VARCHAR(80)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customer_code UNIQUE (code)
);
CREATE INDEX ix_customer_name  ON customer (name);
CREATE INDEX ix_customer_phone ON customer (phone);
CREATE INDEX ix_customer_updated ON customer (updated_at);
