-- Every job a desktop sent (or tried to send) to the Fiery, with its life cycle and the counts
CREATE TABLE print_job (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_job_uuid   VARCHAR(36)  NOT NULL,           -- made by the desktop; makes retries safe
    device_id         BIGINT       NOT NULL REFERENCES device (id),
    operator          VARCHAR(80),                     -- Windows user at the desktop
    customer_id       BIGINT REFERENCES customer (id),
    fiery_job_id      VARCHAR(40),                     -- null for the printer-driver method
    send_method       VARCHAR(20)  NOT NULL,           -- API, DRIVER_API, DRIVER
    file_name         VARCHAR(255) NOT NULL,
    back_file_name    VARCHAR(255),
    job_name          VARCHAR(255),
    paper_pcmid       VARCHAR(40),
    paper_name        VARCHAR(150),
    imposed           BOOLEAN      NOT NULL DEFAULT FALSE,
    quantity_pieces   INTEGER,
    pieces_per_sheet  INTEGER,
    sheets_requested  INTEGER      NOT NULL,           -- copies sent to the Fiery
    duplex            BOOLEAN      NOT NULL DEFAULT FALSE,
    instructions      VARCHAR(2000),
    status            VARCHAR(20)  NOT NULL,
    fiery_state_raw   VARCHAR(100),
    error_message     VARCHAR(2000),
    sent_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    printed_at        TIMESTAMP WITH TIME ZONE,
    removed_at        TIMESTAMP WITH TIME ZONE,
    printed_count     INTEGER,
    waste_count       INTEGER,
    waste_reason      VARCHAR(200),
    counted_by        VARCHAR(80),
    counted_at        TIMESTAMP WITH TIME ZONE,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_print_job_client UNIQUE (device_id, client_job_uuid)
);
CREATE INDEX ix_print_job_customer ON print_job (customer_id);
CREATE INDEX ix_print_job_status   ON print_job (status);
CREATE INDEX ix_print_job_sent     ON print_job (sent_at);
CREATE INDEX ix_print_job_fiery    ON print_job (fiery_job_id);

CREATE TABLE job_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       BIGINT      NOT NULL REFERENCES print_job (id),
    from_status  VARCHAR(20),
    to_status    VARCHAR(20) NOT NULL,
    at           TIMESTAMP WITH TIME ZONE NOT NULL,
    source       VARCHAR(10) NOT NULL,                 -- DESKTOP, POLLER, USER
    note         VARCHAR(500)
);
CREATE INDEX ix_job_history_job ON job_status_history (job_id);
